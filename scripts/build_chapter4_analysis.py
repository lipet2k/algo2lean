"""Bundle modular Chapter 4 proofs for the editor's single-file analysis pane."""

import argparse
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
MODULES = (
    "MatrixMath",
    "StrassenValue",
    "StrassenLinear",
    "StrassenHelpers",
    "StrassenQuadrant",
    "StrassenComposition",
    "StrassenExecution",
    "StrassenDeterminism",
    "StrassenTheorems",
)
DESTINATION = ROOT / "examples/analysis/matrix_strassen.lean"


def build_analysis():
    pieces = [
        "import MatrixStrassenGeneratedPoints\nimport Algo2LeanLib.MatrixHeap\nimport Algo2LeanLib.CallCost\n\n",
        "/-! Generated by scripts/build_chapter4_analysis.py.\n"
        "Edit the corresponding source modules in proofs/chapter4, then rebuild.\n"
        "This bundle is checked against the actual generated algorithm and can\n"
        "be loaded directly into the editor's Lean analysis pane. -/\n",
    ]
    allowed_imports = set(MODULES) | {
        "Std", "Algo2LeanLib.MatrixHeap", "Algo2LeanLib.CallCost", "MatrixStrassenGenerated", "MatrixStrassenGeneratedPoints"
    }
    for module in MODULES:
        path = ROOT / "proofs/chapter4" / (module + ".lean")
        lines = path.read_text(encoding="utf-8").splitlines(keepends=True)
        body = []
        for line in lines:
            if line.startswith("import "):
                imports = line.split()[1:]
                if not set(imports) <= allowed_imports:
                    raise ValueError(f"Unexpected import in {path}: {line.strip()}")
            else:
                body.append(line)
        pieces.append(f"\n/-! Source: proofs/chapter4/{module}.lean -/\n\nsection\n\n")
        pieces.append("".join(body).strip() + "\n\nend\n")
    return "".join(pieces)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the checked-in bundle is stale")
    args = parser.parse_args()
    expected = build_analysis()
    if args.check:
        if not DESTINATION.exists() or DESTINATION.read_text(encoding="utf-8") != expected:
            parser.exit(1, "Chapter 4 analysis is stale; run scripts/build_chapter4_analysis.py\n")
    elif not DESTINATION.exists() or DESTINATION.read_text(encoding="utf-8") != expected:
        DESTINATION.write_text(expected, encoding="utf-8")


if __name__ == "__main__":
    main()
